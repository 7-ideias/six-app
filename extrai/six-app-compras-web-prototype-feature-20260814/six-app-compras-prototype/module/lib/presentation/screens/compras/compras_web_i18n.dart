extension _ComprasWebI18n on BuildContext {
  String comprasT(String key) {
    final String language = Localizations.localeOf(this).languageCode;
    final String? local = switch (language) {
      'en' => _comprasWebEn[key] ?? _comprasWebPt[key],
      'es' => _comprasWebEs[key] ?? _comprasWebPt[key],
      _ => _comprasWebPt[key],
    };
    return t(key, fallback: local);
  }
}

